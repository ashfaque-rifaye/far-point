"""Write the deterministic ~4 min demo trace: myrmidon/replay/demo_session.jsonl.

SYNTHETIC numbers (no camera, no images). Segments:
  0-56 s    Acrobat: lean in to 27 cm -> enlarge_text -> lean back to 45 cm (verified: worked)
  56-100 s  the room goes dark with a light theme, squinting from glare -> dark_mode (worked)
  100-160 s Teams call while a far-look break comes due -> InterruptGate denies it
  160-240 s back to reading: the break proceeds, the user looks away 25 s -> verified

  python scripts/make_demo_trace.py
"""
from __future__ import annotations

import hashlib
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "myrmidon" / "replay" / "demo_session.jsonl"
HZ = 5
DURATION_S = 240
# The near-work bout reaches 45 min (2700 s) about 105 s in, during the Teams call.
SEED_BOUT_S = 2595

ACROBAT = ("acrobat.exe", "paper.pdf - Adobe Acrobat Reader")
TEAMS = ("ms-teams.exe", "Weekly sync | Microsoft Teams")


def state_at(t: float) -> dict:
    s = dict(distance=52.0, ratio=0.97, yaw=0.0, luma=120.0, app=ACROBAT)
    if 8 <= t < 26:
        s.update(distance=27.0, ratio=0.80)
    elif 26 <= t < 56:
        s.update(distance=45.0, ratio=0.96)
    elif 56 <= t < 100:
        s.update(distance=50.0, luma=32.0, ratio=0.68 if t < 66 else 0.93)
    elif 100 <= t < 160:
        s.update(distance=55.0, luma=32.0, ratio=0.95, app=TEAMS)
    elif t >= 160:
        s.update(distance=52.0, luma=32.0, ratio=0.95)
        if 170 <= t < 195:
            s.update(yaw=40.0)
    return s


def rows():
    rng = random.Random(7)
    for i in range(DURATION_S * HZ):
        t = round(i / HZ, 2)
        s = state_at(t)
        blink = i % 19 == 7  # ~16 blinks per minute, one 200 ms frame each
        ratio = 0.3 if blink else s["ratio"] + rng.uniform(-0.015, 0.015)
        proc, title = s["app"]
        yield {
            "t": t, "face": True,
            "distance_cm": round(s["distance"] + rng.uniform(-0.6, 0.6), 2),
            "ear": round(0.28 * ratio, 4), "squint_ratio": round(ratio, 3),
            "yaw": round(s["yaw"] + rng.uniform(-2, 2), 1), "pitch": round(rng.uniform(-3, 3), 1),
            "luma": round(s["luma"] + rng.uniform(-2, 2), 1),
            "process": proc, "title": title, "idle_s": 30.0, "fullscreen": False,
            "theme": "light", "brightness": 55,
        }


def main() -> str:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = {"kind": "header", "version": 1, "seed_bout_s": SEED_BOUT_S, "usual_distance_cm": 52,
              "profile": "demo", "synthetic": True,
              "note": "Synthetic demo trace: numbers only, no images. Generated by scripts/make_demo_trace.py"}
    lines = [json.dumps(header, separators=(",", ":"))]
    lines += [json.dumps(r, separators=(",", ":")) for r in rows()]
    data = ("\n".join(lines) + "\n").encode()
    OUT.write_bytes(data)
    digest = hashlib.sha256(data).hexdigest()
    print(f"wrote {OUT} ({len(lines) - 1} rows, {len(data) // 1024} KB) sha256={digest}")
    return digest


if __name__ == "__main__":
    main()
